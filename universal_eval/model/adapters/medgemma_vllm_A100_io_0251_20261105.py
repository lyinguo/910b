"""Own MedGemma full-chat input and native Rust incremental-output semantics.

The two BOS tokens are generated by the unchanged own template plus authentic
Rust postprocessor. No token is manually prepended/removed, and no learned
model execution, score, report or workbook publication is performed here.
"""
import hashlib
import json
from pathlib import Path

import numpy as np
import torch
from PIL import Image
from jinja2.sandbox import ImmutableSandboxedEnvironment
from tokenizers import Tokenizer
from tokenizers.decoders import DecodeStream
from torchvision.transforms.v2 import functional as TV
from torchvision.transforms import InterpolationMode


def sha(path):
    digest=hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda:stream.read(8*1024*1024),b''):
            digest.update(block)
    return digest.hexdigest()


def fingerprint(tensor):
    value=tensor.detach().cpu().contiguous().reshape(-1).view(torch.uint8)
    return hashlib.sha256(value.numpy().tobytes()).hexdigest()


class OwnMedGemmaIO:
    def __init__(self, root, own_resource_sha256, expected_full_image_sequence):
        from transformers import AutoProcessor
        self.root=Path(root).resolve()
        for name,digest in own_resource_sha256.items():
            assert Path(name).name==name and sha(self.root/name)==digest,name
        self.tokenizer=Tokenizer.from_file(str(self.root/'tokenizer.json'))
        self.processor=AutoProcessor.from_pretrained(str(self.root),local_files_only=True)
        assert type(self.processor).__name__=='Gemma3Processor'
        assert self.processor.image_seq_length==256
        self.full_image_sequence=self.processor.full_image_sequence
        assert self.full_image_sequence==expected_full_image_sequence
        self.template_text=(self.root/'chat_template.jinja').read_text()
        environment=ImmutableSandboxedEnvironment(trim_blocks=True,lstrip_blocks=True)
        environment.globals['raise_exception']=lambda message:(_ for _ in ()).throw(ValueError(message))
        self.template=environment.from_string(self.template_text)
        cfg=self.processor.image_processor.to_dict()
        assert cfg['size']=={'height':896,'width':896} and cfg['resample']==2
        assert cfg['do_resize'] and cfg['do_rescale'] and cfg['do_normalize']
        # The authentic processor serializes the RGB-uniform mean/std as .5
        # in this runtime; its source file may contain three identical values.
        # Accept only these exact equal-channel representations, no tolerance.
        assert cfg['image_mean'] in (.5,[.5,.5,.5],(.5,.5,.5))
        assert cfg['image_std'] in (.5,[.5,.5,.5],(.5,.5,.5))
        assert cfg['rescale_factor']==1/255 and not cfg.get('do_pan_and_scan',False)
        # Check the genuine installed native API, not a replacement decoder.
        probe=DecodeStream(ids=[2],skip_special_tokens=True)
        assert hasattr(probe,'step')

    def render(self, prompt):
        conversation=[{'role':'user','content':[{'type':'image'},
                                               {'type':'text','text':prompt}]}]
        rendered=self.template.render(messages=conversation,
            add_generation_prompt=True,bos_token='<bos>',eos_token='<eos>',
            pad_token='<pad>',tools=None)
        assert rendered.count('<start_of_image>')==1
        rendered=rendered.replace('<start_of_image>',self.full_image_sequence)
        # LLM.chat explicitly renders text (tokenize=False), then its MM
        # TokenizeParams add_special_tokens=True applies this own postprocessor.
        ids=self.tokenizer.encode(rendered,add_special_tokens=True).ids
        assert ids[:2]==[2,2] and ids.count(2)==2 and ids.count(262144)==256
        soft=[i for i,value in enumerate(ids) if value==262144]
        assert soft==list(range(soft[0],soft[0]+256))
        assert ids[soft[0]-1]==255999 and ids[soft[-1]+1]==256000
        return rendered,ids,soft[0]

    def pixels(self, media_path):
        path=Path(media_path).resolve()
        media_sha=sha(path)
        with Image.open(path) as image:
            image=image.convert('RGB')
            source=torch.from_numpy(np.asarray(image).copy()).permute(2,0,1)
        resized=TV.resize(source,[896,896],interpolation=InterpolationMode.BILINEAR,
                          antialias=True)
        value=((resized.float()-127.5)/127.5).bfloat16()[None]
        assert value.shape==(1,3,896,896)
        return value,media_sha,fingerprint(value),str(path)

    def decode(self, prompt_ids, output_ids, finish_reason):
        """Original FastIncrementalDetokenizer semantics for these fixed params.

        stop=[], min_tokens=0, skip_special_tokens=True and
        include_stop_str_in_output=False. Priming with the full prompt preserves
        spaces and incomplete UTF-8 behavior at the original budget boundary.
        Warnings and all raw token IDs are retained by the caller.
        """
        assert finish_reason in ('stop','length')
        assert output_ids
        if finish_reason=='stop':
            assert output_ids[-1] in (1,106)
            decode_ids=output_ids[:-1]
        else:
            decode_ids=output_ids
        stream=DecodeStream(ids=list(prompt_ids),skip_special_tokens=True)
        text='';warnings=[]
        for index,token_id in enumerate(decode_ids):
            try:
                fragment=stream.step(self.tokenizer,int(token_id))
            except (OverflowError,TypeError) as error:
                # The genuine original protected_step catches these exceptions.
                warnings.append({'output_position':index,'token_id':int(token_id),
                                 'kind':'original_protected_invalid_token',
                                 'error':str(error)})
                fragment=None
            except Exception as error:
                if not str(error).startswith('Invalid prefix encountered'):
                    raise
                warnings.append({'output_position':index,'token_id':int(token_id),
                                 'kind':'original_protected_invalid_UTF8_prefix',
                                 'error':str(error)})
                stream=DecodeStream(skip_special_tokens=True)
                fragment=stream.step(self.tokenizer,int(token_id))
            text+=fragment or ''
        return text,warnings
